#!/usr/bin/env python3
"""The pieces' recipes as they have been (every version of amb.c's PIECES since 1.0.0, from git), as fingerprints:
for each, its parameter count and one FNV-1a hash a piece over its values (Tune and MIDI out left out: the player's).
project.c reads them: a saved piece that matches one of its own past recipes was never changed, and takes today's.
  tools/gen_recipe_prints.py > firmware/src/app/recipe_prints.h"""
import re, subprocess, sys

SKIP = {16, 17}                      # P_TUNE, P_MIDI


def pieces(src):
    m = re.search(r'PIECES\[EN_NPIECES\]\s*=\s*\{(.*?)\n\};', src, re.S)
    if not m:
        return None
    rows = re.findall(r'\{\s*"([^"]+)",\s*\{([^}]*)\}\s*\}', m.group(1))
    out = []
    for name, body in rows:
        vals = [int(t) for t in re.findall(r'-?\d+', body)]
        out.append((name, vals))
    return out if len(out) == 8 else None


def fnv(vals):
    h = 2166136261
    for i, v in enumerate(vals):
        if i in SKIP:
            continue
        u = v & 0xFFFF
        for b in (u & 0xFF, u >> 8):
            h = ((h ^ b) * 16777619) & 0xFFFFFFFF
    return h


def main():
    commits = subprocess.run(['git', 'log', '--format=%H', 'v1.0.0^..HEAD', '--', 'firmware/src/dsp/amb.c'],
                             capture_output=True, text=True, check=True).stdout.split()
    seen, prints = set(), []
    srcs = [open('firmware/src/dsp/amb.c').read()]
    for c in commits:
        r = subprocess.run(['git', 'show', c + ':firmware/src/dsp/amb.c'], capture_output=True, text=True)
        if r.returncode == 0:
            srcs.append(r.stdout)
    for src in srcs:
        p = pieces(src)
        if not p:
            continue
        n = len(p[0][1])
        if any(len(v) != n for _, v in p):
            continue
        key = (n, tuple(fnv(v) for _, v in p))
        if key not in seen:
            seen.add(key)
            prints.append(key)
    w = sys.stdout.write
    w('/* generated by tools/gen_recipe_prints.py: the pieces\' recipes as they have been since 1.0.0 (their parameter\n'
      ' * count, a hash a piece; Tune and MIDI out left out). Do not edit */\n')
    w('#define RECIPE_PRINTS %d\n' % len(prints))
    w('static const struct { uint16_t n; uint32_t h[8]; } RECIPE_PRINT[RECIPE_PRINTS] = {\n')
    for n, hs in prints:
        w('    {%d, {%s}},\n' % (n, ', '.join('0x%08Xu' % h for h in hs)))
    w('};\n')


main()
