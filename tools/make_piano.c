#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#define FM1_DSP_DATA
#define SAMPLE_DRUM_PADS 8
#include "sample_metadata.inc"
#include "fm1_sea.h"
#include "sea_encode.h"
static int16_t *load(const char *path, unsigned *frames)
{
    FILE *f = fopen(path, "rb");
    uint8_t h[44];
    long n;
    int16_t *pcm;
    if (!f || fread(h, 1, 44, f) != 44) exit(1);
    fseek(f, 0, SEEK_END), n = (ftell(f) - 44) / 2, fseek(f, 44, SEEK_SET);
    pcm = malloc((size_t)n * 2);
    if (fread(pcm, 2, (size_t)n, f) != (size_t)n) exit(1);
    fclose(f);
    *frames = (unsigned)n;
    return pcm;
}
int main(int argc, char **argv)
{
    unsigned frames[3], blocks, i, k;
    int16_t *pcm[3];
    uint8_t *enc[3];
    FILE *f;
    if (argc < 5) return 1;
    for (k = 0; k < 3; k++) {
        pcm[k] = load(argv[1 + k], &frames[k]);
        enc[k] = fm1_sea_encode(pcm[k], frames[k], sample_dqt);
    }
    if (frames[0] != frames[1] || frames[1] != frames[2]) return 2;
    blocks = (frames[0] + 319) / 320;
    f = fopen(argv[4], "w");
    fprintf(f, "/* Generated by tools/make_piano.c: the Piano voice's three notes (C3, C5 and C6 of the Kawai grand piano of\n"
               " * Versilian Studios' Virtual Community Sample Library, CC0, from Felucca, whose files name them C2, C4 and C5:\n"
               " * 22.05 kHz mono, the first 2.38 s of each, faded out over the last 0.4 s), %u samples each, as %u SEA5 chunks\n"
               " * of 228 bytes (SEA: Copyright (c) 2025 Dani Biro, MIT; the quantiser table is the Rain loop's). Do not edit. */\n",
            frames[0], blocks);
    fprintf(f, "#define PN_N %uu                              /* (each note's samples) */\n", frames[0]);
    for (k = 0; k < 3; k++) {
        fprintf(f, "static const uint8_t PN_DATA%u[%u] = {\n", k, blocks * 228);
        for (i = 0; i < blocks * 228; i++) fprintf(f, "%u,%s", enc[k][i], (i & 31) == 31 ? "\n" : "");
        fprintf(f, "};\n");
    }
    fclose(f);
    printf("%u samples, %u chunks, %u bytes each\n", frames[0], blocks, blocks * 228);
    return 0;
}
